CREATE TABLE IF NOT EXISTS attestation (
    id VARCHAR(255),
    mois VARCHAR(255),
    annee VARCHAR(255),
    job_id VARCHAR(255),
    date_creation VARCHAR(255),
    code_position VARCHAR(255),
    nom_agent VARCHAR(255),
    num_somme VARCHAR(255),
    num_cnie VARCHAR(255),
    code_localite VARCHAR(255),
    adresse VARCHAR(255),
    code_sexe VARCHAR(255),
    code_pays VARCHAR(255),
    date_naissance VARCHAR(255),
    date_recrutement VARCHAR(255),
    date_rachat VARCHAR(255),
    date_limite VARCHAR(255),
    motif_radiation VARCHAR(255),
    code_imputation VARCHAR(255),
    residence VARCHAR(255),
    code_poste VARCHAR(255),
    mode_reglement VARCHAR(255),
    base_imposable VARCHAR(255),
    saisissable VARCHAR(255),
    brut_annuel VARCHAR(255),
    net_annuel VARCHAR(255),
    date_effet_situation VARCHAR(255),
    code_statut VARCHAR(255),
    code_grade VARCHAR(255),
    echelon VARCHAR(255),
    point_indice VARCHAR(255),
    code_zone VARCHAR(255),
    code_fonction VARCHAR(255),
    code_position_detach VARCHAR(255),
    code_departement VARCHAR(255),
    avance VARCHAR(255),
    pension VARCHAR(255),
    code_grade_pension VARCHAR(255),
    indice_pension VARCHAR(255),
    echelon_pension VARCHAR(255),
    code_situat_famil VARCHAR(255),
    nbre_enfant VARCHAR(255),
    deductions VARCHAR(255),
    code_mutuel_sc VARCHAR(255),
    taux_mutuel_sc VARCHAR(255),
    code_mutuelle_sm VARCHAR(255),
    taux_mutuelle_sm VARCHAR(255),
    date_dernier_mouvement VARCHAR(255),
    taux_prime_anci VARCHAR(255),
    num_compte VARCHAR(255),
    date_last_update VARCHAR(255),
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS attestation_rejection (
    id                BIGINT AUTO_INCREMENT PRIMARY KEY,
    job_execution_id  BIGINT       NOT NULL,
    step_name         VARCHAR(255) NOT NULL,
    raw_content       TEXT,
    reason            TEXT,
    created_at        TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
